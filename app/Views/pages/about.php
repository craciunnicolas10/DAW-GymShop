            <h2>Creatina: cel mai studiat supliment</h2>
            <p>
                Creatina monohidrat crește rezervele de fosfocreatină din mușchi, ceea ce ajută la refacerea rapidă a energiei
                (ATP) în eforturile scurte și intense, precum ridicarea greutăților sau sprinturile. Este unul dintre puținele
                suplimente cu efecte demonstrate de sute de studii.
            </p>
            <p>
                Nu este necesară o fază de „încărcare”: o doză zilnică de 3-5 g, luată constant, saturează mușchii în aproximativ
                3-4 săptămâni. Momentul zilei contează mai puțin decât regularitatea.
            </p>
